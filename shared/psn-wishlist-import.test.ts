import { describe, expect, it } from 'vitest';
import {
  extractCardTitleAndPrices,
  parsePsnWishlistSource,
  toPsnWishlistRecord,
} from './psn-wishlist-import.js';

describe('extractCardTitleAndPrices', () => {
  it('extracts clean title and TWD prices from noisy PS Store card innerText', () => {
    const res = extractCardTitleAndPrices(
      'PS5\nPS4\n艾爾登法環\n-40%\nNT$1,074\nNT$1,790\n加入購物車'
    );
    expect(res.title).toBe('艾爾登法環');
    expect(res.currentPriceTwd).toBe(1074);
    expect(res.regularPriceTwd).toBe(1790);
    expect(res.discountPercent).toBe(40);
  });
});

describe('parsePsnWishlistSource', () => {
  it('parses JSON array generated by the 1-line Console snippet', () => {
    const snippetOutput = JSON.stringify([
      {
        href: 'https://store.playstation.com/zh-hant-tw/product/HP0700-PPSA04609_00-ELDENRING0000000',
        text: 'PS5\n艾爾登法環\n-40%\nNT$1,074\nNT$1,790',
        linkText: '艾爾登法環',
        aria: '',
        img: 'https://image.api.playstation.com/vulcan/elden.jpg',
      },
      {
        href: 'https://store.playstation.com/zh-hant-tw/concept/10008736',
        text: 'PS5\n黑神話：悟空\nNT$1,790',
        linkText: '黑神話：悟空',
        aria: '',
        img: 'https://image.api.playstation.com/vulcan/wukong.jpg',
      },
    ]);

    const items = parsePsnWishlistSource(snippetOutput);
    expect(items).toHaveLength(2);
    expect(items[0]).toMatchObject({
      title: '艾爾登法環',
      productId: 'HP0700-PPSA04609_00-ELDENRING0000000',
      titleId: 'PPSA04609_00',
      currentPriceTwd: 1074,
      regularPriceTwd: 1790,
      discountPercent: 40,
    });
    expect(items[1]).toMatchObject({
      title: '黑神話：悟空',
      conceptId: '10008736',
      currentPriceTwd: 1790,
    });

    const rec = toPsnWishlistRecord(items[0], 1000);
    expect(rec.id).toBe('psn_HP0700-PPSA04609_00-ELDENRING0000000');
    expect(rec.platform).toBe('PS');
    expect(rec.source).toBe('psn');
  });

  it('still supports SSR __NEXT_DATA__ apolloState format', () => {
    const nextData = {
      props: {
        pageProps: {
          apolloState: {
            ROOT_QUERY: {
              'wishlistItemsRetrieve({"pageArgs":{"size":100}})': {
                items: [{ __ref: 'Product:HP0177-PPSA01521_00-0000000000000000' }],
              },
            },
            'Product:HP0177-PPSA01521_00-0000000000000000': {
              __typename: 'Product',
              id: 'HP0177-PPSA01521_00-0000000000000000',
              name: '地平線 西域禁地',
              price: { basePrice: 'NT$1,790', discountedPrice: 'NT$895', discountText: '-50%' },
            },
          },
        },
      },
    };
    const html = `<!DOCTYPE html><html><body><script id="__NEXT_DATA__" type="application/json">${JSON.stringify(
      nextData
    )}</script></body></html>`;

    const items = parsePsnWishlistSource(html);
    expect(items).toHaveLength(1);
    expect(items[0].title).toBe('地平線 西域禁地');
  });

  it('throws friendly error explaining dynamic rendering when empty shell HTML is pasted', () => {
    expect(() => parsePsnWishlistSource('<html><body><title>收藏清單</title></body></html>')).toThrow(
      /Console/
    );
  });
});
